/** v20 cross-component invariants. Execute with node scripts/verify-answer-lanes-v20.mjs */
import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
const root=resolve(import.meta.dirname,'..');
const read=(p)=>readFileSync(resolve(root,p),'utf8');
const q=read('src/ui-react/components/gameplay/shared/question-shell.tsx');
const floor=read('src/ui-react/components/gameplay/citizens/ChoiceSpotlights.tsx');
const position=read('src/ui-react/components/gameplay/shared/citizen-helpers.ts');
const citizen=read('src/ui-react/components/gameplay/citizens/CitizenPlaza.tsx');
const host=read('src/ui-react/components/visual/HostMascotLayer.tsx');
const stage=read('src/ui-react/components/gameplay/shared/answer-stage-layout.ts');
const css=read('src/ui-react/styles/answer-zones-question-v20.css');
const main=read('src/ui-react/main.tsx');
let n=0;const check=(v,m)=>{assert.ok(v,m);n++};
check(q.includes('qshell-v20') && q.includes('qshell-choices'),'shared shell opts into v20');
check(q.indexOf('className="qshell-topline"') < q.indexOf('<QuestionPhaseTimer') && q.indexOf('<QuestionPhaseTimer') < q.indexOf('<h2 className="qshell-title"'), 'banner then full timer then question');
check(!q.includes('<PrivateStreamerAnswerDock'), 'host removed from question HUD');
check(host.includes('<PrivateStreamerAnswerDock />') && host.includes('qshell-host-bubble-v20'), 'host bubble anchored to the host stage');
check(/gameplay-choice-spotlights-v19 audience-answer-lanes-v20/.test(floor),'floor uses lane component');
check(/getCorrectOptionNumber/.test(floor) && /gameplay-choice-spotlight-\$\{resultState\}/.test(floor),'reveal changes lane state');
check(/ANSWER_STAGE_LAYOUT/.test(floor) && /ANSWER_STAGE_LAYOUT/.test(position), 'floor and citizens share stage coordinates');
check(/leftPercent: 13/.test(stage) && /widthPercent: 74/.test(stage),'all four lane centers stay inside spectator safe area');
check(/optionGroupSizes/.test(citizen) && /groupSize: optionGroupSizes/.test(citizen),'crowd density is measured per answer');
check(/phase === 'scoring'/.test(citizen) && !/setTimeout\(\(\) => setShowScoringAudience/.test(citizen),'crowd holds at their answer until host opens scoreboard');
check(/grid-template-columns: repeat\(4, minmax\(0, 1fr\)\)/.test(css),'four horizontal equal answers');
check(/direction: ltr !important; \/\* choice 1/.test(css),'RTL does not flip Twitch numbering');
check(/grid-template-rows: minmax\(0,1fr\) clamp/.test(css),'challenge gets larger flexible vertical space');
check(/\.gameplay-question-timer \{/.test(css) && /max-width: none !important;/.test(css),'timer uses full question width');
check(!floor.includes('floor-answer-pad'),'old floor circles removed');
check(main.includes("'./styles/answer-zones-question-v20.css'") && main.indexOf('answer-zones-question-v20.css')>main.indexOf('game-show-polish-v19.css'),'v20 styles loaded last');
check(existsSync(resolve(root,'src/ui-react/styles/answer-zones-question-v20.css')),'style asset included');
console.log(`v20 question + audience lane invariants PASS (${n})`);
