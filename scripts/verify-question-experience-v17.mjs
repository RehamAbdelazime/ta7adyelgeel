import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

const read = (file) => readFileSync(resolve(file), 'utf8');
const shell = read('src/ui-react/components/gameplay/shared/question-shell.tsx');
const food = read('src/ui-react/components/gameplay/minigames/FoodOriginScreen.tsx');
const maze = read('src/ui-react/components/gameplay/minigames/MazeGatesScreen.tsx');
const styles = read('src/ui-react/styles/question-experience-v17.css');
const main = read('src/ui-react/main.tsx');
const translations = read('src/game-core/localization/translations.ts');
const keys = read('src/game-core/localization/locale-types.ts');

assert.match(shell, /export type QuestionLayout = 'legacy' \| 'choice' \| 'focus' \| 'interactive'/);
assert.match(shell, /layout = 'legacy'/, 'Legacy default must protect other games');
assert.match(shell, /qshell-layout-\$\{layout\}/, 'Visual variants should be generated by the shared shell');
assert.match(shell, /getCorrectOptionNumber\(miniGame\)/, 'Shared answer logic must remain in the shell');
assert.match(shell, /onClick=\{actions.skipPhase\}/, 'Reveal Next functionality retained');
assert.match(shell, /miniGame\.officialAnswerCount/, 'Live answer counter retained');
assert.match(shell, /remainingLabel\(remainingSeconds\)/, 'Countdown aria text must be localized');
assert.match(food, /layout="choice"/, 'Food Origin should opt into choice layout');
assert.match(maze, /layout="interactive"/, 'Maze Gates should opt into interactive layout');
assert.match(maze, /t\('gameplay\.maze\.boardLabel'\)/, 'Maze accessibility label should be localized');
assert.match(main, /import '\.\/styles\/question-experience-v17\.css'/);
assert.match(styles, /\.gameplay-question-shell\.qshell-v17/);
assert.match(styles, /qshell-layout-interactive/);
assert.match(styles, /qshell-layout-choice/);
assert.match(styles, /prefers-reduced-motion/);
assert.match(translations, /"gameplay\.timer\.remaining": "\{\{seconds\}\} seconds remaining"/);
assert.match(translations, /"gameplay\.timer\.remaining": "متبقي \{\{seconds\}\} ثانية"/);
assert.match(keys, /'gameplay\.timer\.remaining'/);
// Guard: no changes to scoring APIs, command parsing or game state here.
const optIns = (read('src/ui-react/components/gameplay/minigames/FoodOriginScreen.tsx') +
  read('src/ui-react/components/gameplay/minigames/MazeGatesScreen.tsx')).match(/layout="(choice|interactive|focus)"/g) || [];
assert.equal(optIns.length, 2, 'Exactly two pilot games opt into layout variants');
console.log('Question Experience v17 structural contract PASS — pilot games Food Origin + Maze Gates');
